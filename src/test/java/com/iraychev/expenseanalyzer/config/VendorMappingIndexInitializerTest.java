package com.iraychev.expenseanalyzer.config;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.dao.DuplicateKeyException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.util.List;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

/** Runs the production cleanup SQL against an in-memory H2 (PostgreSQL mode) table holding duplicate vendors. */
class VendorMappingIndexInitializerTest {

    private JdbcTemplate jdbc;
    private VendorMappingIndexInitializer initializer;

    @BeforeEach
    void setUp() {
        DriverManagerDataSource ds = new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(ds);
        jdbc.execute("create schema if not exists expense_analyzer");
        jdbc.execute("create table expense_analyzer.vendor_category_mapping "
                + "(id bigint generated by default as identity primary key, vendor varchar(255), category varchar(255))");
        initializer = new VendorMappingIndexInitializer(jdbc, new DataSourceTransactionManager(ds), "expense_analyzer");
    }

    private void insert(String vendor, String category) {
        jdbc.update("insert into expense_analyzer.vendor_category_mapping (vendor, category) values (?, ?)", vendor, category);
    }

    private List<String> rows() {
        return jdbc.queryForList("select vendor || '=' || coalesce(category, 'null') from "
                + "expense_analyzer.vendor_category_mapping order by id", String.class);
    }

    @Test
    void mergesDuplicatesPrefersRealCategoryAndCreatesUniqueIndex() {
        insert("starbucks", "Other");          // duplicate: the real category below must win
        insert("starbucks", "Restaurants and bars");
        insert("starbucks", "Shopping");       // later duplicate of a real category is dropped
        insert("lidl", "Supermarkets");
        insert("lidl", "Supermarkets");
        insert("kaufland", "Supermarkets");
        insert("Unknown Vendor", "Shopping");  // placeholder rows are removed
        insert("unknown vendor", "Other");
        insert("ghost", "Other");
        insert("ghost", "Other");              // all-Other duplicates keep the first

        initializer.run();

        assertEquals(List.of("starbucks=Restaurants and bars", "lidl=Supermarkets", "kaufland=Supermarkets",
                "ghost=Other"), rows());
        assertThrows(DuplicateKeyException.class, () -> insert("lidl", "Shopping"));
    }

    @Test
    void isIdempotentAndWorksOnCleanTable() {
        insert("lidl", "Supermarkets");

        initializer.run();
        initializer.run();

        assertEquals(List.of("lidl=Supermarkets"), rows());
    }

    @Test
    void startupHookNeverThrowsEvenWhenTableIsMissing() {
        jdbc.execute("drop table expense_analyzer.vendor_category_mapping");
        initializer.afterSingletonsInstantiated();
    }
}
